"""Package Raid's unmodified CC BY 4.0 Lab glTF/JPEGs for an offline PhET build."""
from pathlib import Path
import argparse,base64,json,hashlib,zipfile
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--archive',type=Path,help='Optional original lab.zip to extract into assets/lab')
args=parser.parse_args()
folder=root/'assets/lab'
if args.archive:
 folder.mkdir(parents=True,exist_ok=True)
 with zipfile.ZipFile(args.archive) as archive:
  for item in archive.infolist():
   name=Path(item.filename)
   if name.is_absolute() or '..' in name.parts:raise ValueError('Unsafe archive path')
   if not item.is_dir():
    destination=folder/name;destination.parent.mkdir(parents=True,exist_ok=True);destination.write_bytes(archive.read(item))
gltf=json.loads((folder/'scene.gltf').read_text())
assert gltf['asset']['version']=='2.0' and not gltf.get('extensionsRequired')
def b64(path):return base64.b64encode(path.read_bytes()).decode('ascii')
data={'gltf':gltf,'buffers':[b64(folder/item['uri']) for item in gltf['buffers']],
      'images':['data:image/jpeg;base64,'+b64(folder/item['uri']) for item in gltf['images']]}
p=root/'js/common/data/LabSceneData.js'
p.write_text('/* eslint-disable */\n// Generated by scripts/prepare-lab.py; regenerate from assets/lab, do not edit.\n// Lab model and original textures by Raid, CC-BY-4.0, https://sketchfab.com/raid\n// Source: https://sketchfab.com/3d-models/lab-80d760e688c84cda8077bb53ae15956f\n// Software wrapper: GPL-3.0-only. Asset license and attribution: assets/lab/license.txt\nconst LabSceneData = '+json.dumps(data,separators=(',',':'))+';\nexport default LabSceneData;\n')
manifest={str(p.relative_to(folder)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(folder.rglob('*')) if p.is_file() and p.name not in ['SHA256SUMS.json']}
(folder/'SHA256SUMS.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Packaged original Lab geometry and textures:',p.stat().st_size,'bytes; no image re-encoding or resizing')
